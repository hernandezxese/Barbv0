export interface ElementalMultiplierResult {
  multiplier: number;
  elementalMultiplier: number;
  hasStab: boolean;
  message: string;
  badgeLabel: string;
  tier: 'ultra' | 'super' | 'stab' | 'neutral' | 'resist' | 'double_resist';
}

const SINGLE_ADVANTAGES: Record<ElementType, ElementType[]> = {
  fuego: ['planta', 'hielo', 'tierra'],
  agua: ['fuego', 'tierra'],
  planta: ['agua', 'tierra'],
  viento: ['planta', 'agua'],
  tierra: ['viento', 'hielo'],
  hielo: ['planta', 'viento'],
  sagrado: ['fuego', 'tierra', 'agua', 'planta', 'viento', 'hielo'],
  normal: []
};

const SINGLE_RESISTANCES: Record<ElementType, ElementType[]> = {
  fuego: ['fuego', 'planta', 'hielo'],
  agua: ['agua', 'fuego', 'hielo'],
  planta: ['planta', 'agua', 'tierra'],
  viento: ['viento', 'tierra'],
  tierra: ['tierra', 'viento'],
  hielo: ['hielo', 'agua'],
  sagrado: [],
  normal: []
};

function getSingleElementFactor(attacker: ElementType, defender: ElementType): number {
  if (SINGLE_ADVANTAGES[attacker]?.includes(defender)) {
    return attacker === 'sagrado' ? 1.5 : 2.0;
  }
  if (SINGLE_RESISTANCES[defender]?.includes(attacker)) {
    return 0.5;
  }
  return 1.0;
}

// Dynamic Elemental Affinity Matrix (Dual-type defender + STAB support)
export function getElementalMultiplier(
  attackerSkillElement: ElementType,
  defenderPrimary: ElementType,
  defenderSecondary?: ElementType,
  attackerSpiritPrimary?: ElementType,
  attackerSpiritSecondary?: ElementType
): ElementalMultiplierResult {
  const factor1 = getSingleElementFactor(attackerSkillElement, defenderPrimary);
  const factor2 = defenderSecondary && defenderSecondary !== defenderPrimary
    ? getSingleElementFactor(attackerSkillElement, defenderSecondary)
    : 1.0;

  const elementalMultiplier = Math.max(0.25, Math.min(4.0, Number((factor1 * factor2).toFixed(2))));

  const hasStab = Boolean(
    attackerSkillElement !== 'normal' &&
    (attackerSpiritPrimary === attackerSkillElement || attackerSpiritSecondary === attackerSkillElement)
  );

  const multiplier = Number((elementalMultiplier * (hasStab ? 1.25 : 1.0)).toFixed(2));

  let message = '';
  let badgeLabel = `x${multiplier.toFixed(multiplier % 1 === 0 ? 1 : 2)}`;
  let tier: ElementalMultiplierResult['tier'] = 'neutral';

  if (elementalMultiplier >= 3.0) {
    tier = 'ultra';
    message = '¡AFINIDAD DEVASTADORA! ¡Daño elemental extremo!';
    badgeLabel = `¡CRÍTICO ELEMENTAL x${multiplier}!`;
  } else if (elementalMultiplier > 1.0) {
    tier = 'super';
    message = '¡Es súper eficaz por afinidad elemental!';
    badgeLabel = `SÚPER EFICAZ x${multiplier}`;
  } else if (elementalMultiplier < 0.5) {
    tier = 'double_resist';
    message = 'El rival resiste enormemente este elemento...';
    badgeLabel = `MUY RESISTIDO x${multiplier}`;
  } else if (elementalMultiplier < 1.0) {
    tier = 'resist';
    message = 'No es muy eficaz por afinidad...';
    badgeLabel = `POCO EFICAZ x${multiplier}`;
  } else if (hasStab) {
    tier = 'stab';
    message = '¡Bonificación por afinidad natural (+25%)!';
    badgeLabel = `AFÍN x${multiplier}`;
  } else {
    tier = 'neutral';
    badgeLabel = 'NEUTRO x1.0';
  }

  return {
    multiplier,
    elementalMultiplier,
    hasStab,
    message,
    badgeLabel,
    tier,
  };
}

export function getWeaknessesForSpirit(primary: ElementType, secondary?: ElementType): ElementType[] {
  const allAttackElements: ElementType[] = ['agua', 'fuego', 'planta', 'viento', 'tierra', 'hielo'];
  return allAttackElements.filter(el => {
    const res = getElementalMultiplier(el, primary, secondary);
    return res.elementalMultiplier > 1.0;
  });
}

